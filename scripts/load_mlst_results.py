from pathlib import Path

import psycopg2


"""
Load MLST typing results into the BHRe PostgreSQL database.

This script scans all sample directories in the BHRe project structure,
locates MLST result files generated by the MLST typing pipeline, parses
their content, and stores the results in the `mlst_results` table.

Main workflow
-------------
1. Iterate through all sample directories.
2. Locate the MLST result file (`mlst.tsv`).
3. Parse species, sequence type (ST), and allele profiles.
4. Insert MLST results into PostgreSQL.
5. Commit the transaction.

Author
------
Mareme SARR
Bioinformatics Engineer
Hospices Civils de Lyon
"""


# ============================================================================
# Configuration
# ============================================================================

ROOT_DIR = Path("/data/msarr/BD_BHRe")

DB_CONFIG = {
    "dbname": "bd_bhre",
    "user": "msarr",
    "host": "localhost",
    "port": 55432,
}


# ============================================================================
# MLST import workflow
# ============================================================================

def load_mlst_results():
    """
    Import MLST results into the PostgreSQL database.

    The function scans each sample directory located under `ROOT_DIR`
    and searches for the expected MLST result file:

        <sample_dir>/mlst/mlst.tsv

    Each non-empty line of the file is parsed according to the standard
    MLST output format:

        sequence_file species ST allele_profile...

    Parsed results are inserted into the `mlst_results` table.

    Raises
    ------
    FileNotFoundError
        If the root directory does not exist.

    psycopg2.Error
        If a database error occurs during insertion.
    """

    if not ROOT_DIR.exists():
        raise FileNotFoundError(f"Root directory not found: {ROOT_DIR}")

    conn = psycopg2.connect(**DB_CONFIG)
    cur = conn.cursor()

    try:
        # Remove previous MLST results before reloading.
        cur.execute("TRUNCATE TABLE mlst_results;")

        for sample_dir in ROOT_DIR.iterdir():

            if not sample_dir.is_dir():
                continue

            sample_id = sample_dir.name
            mlst_file = sample_dir / "mlst" / "mlst.tsv"

            if not mlst_file.exists():
                continue

            n_records = 0

            with open(
                mlst_file,
                "r",
                encoding="utf-8",
                errors="replace"
            ) as handle:

                for line in handle:

                    line = line.strip()

                    if not line:
                        continue

                    parts = line.split()

                    # Skip malformed lines.
                    if len(parts) < 3:
                        continue

                    sequence_file = parts[0]
                    species = parts[1]
                    st = parts[2]

                    # Remaining columns correspond to the allele profile.
                    alleles = (
                        " ".join(parts[3:])
                        if len(parts) > 3
                        else None
                    )

                    cur.execute("""
                        INSERT INTO mlst_results (
                            sample_id,
                            sequence_file,
                            species,
                            st,
                            alleles,
                            source_file
                        )
                        VALUES (
                            %s, %s, %s, %s, %s, %s
                        )
                    """, (
                        sample_id,
                        sequence_file,
                        species,
                        st,
                        alleles,
                        str(mlst_file)
                    ))

                    n_records += 1

            print(
                f"[MLST_RESULTS] "
                f"{sample_id} -> {n_records} record(s)"
            )

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()

    print("MLST results loading completed successfully.")


if __name__ == "__main__":
    load_mlst_results()